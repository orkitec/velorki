# --------------------------------------------------------------- the ui tree

dump() {
  local try
  for try in 1 2 3; do
    A shell uiautomator dump /sdcard/velorki-ui.xml > /dev/null 2>&1 || true
    if A shell cat /sdcard/velorki-ui.xml > "$WORK/ui.xml" 2> /dev/null \
      && [ -s "$WORK/ui.xml" ]; then
      return 0
    fi
    sleep 1
  done
  return 1
}

# node <regex> [nth] -> "cx cy x1 y1 x2 y2", matched against content-desc, text
# and the hint of every node in a fresh dump.
node() { dump && python3 "$HERE/ui.py" find "$WORK/ui.xml" "$1" "${2:-0}"; }

has() { node "$1" "${2:-0}" > /dev/null 2>&1; }

tap_xy() { A shell input tap "$1" "$2"; }

tap() {  # tap <regex> [nth] [fraction of the node's height, default 50]
  local p fy=${3:-50}
  p=$(node "$1" "${2:-0}") || { printf '::error::no node matching %q\n' "$1" >&2; return 1; }
  # `set --` overwrites the positional parameters, so read $3 before it.
  set -- $p
  tap_xy "$1" "$(( $4 + ($6 - $4) * fy / 100 ))"
}

# Waits until <regex> is on screen. wait_for <regex> [seconds] [message]
wait_for() {
  local pattern=$1 limit=${2:-60} i
  for ((i = 0; i < limit; i++)); do
    has "$pattern" && return 0
    sleep 1
  done
  printf '::error::%s\n' "${3:-timed out waiting for /$pattern/}" >&2
  return 1
}

wait_gone() {
  local pattern=$1 limit=${2:-60} i
  for ((i = 0; i < limit; i++)); do
    has "$pattern" || return 0
    sleep 1
  done
  return 1
}

# A snackbar ("… deleted", "… added to the library") sits over the bottom of
# the screen for a good while and swallows taps meant for the button under it.
# Swiping it out to the left dismisses it.
SNACK="$(ui snack)"

dismiss_snackbar() {
  local i p x y
  for i in 1 2 3 4; do
    p=$(node "$SNACK") || return 0
    # Read the coordinates out before `set --` touches the arguments; the bar
    # floats at a different height on a screen that has a bottom bar of its own.
    x=${p%% *}
    # Drag from the bar's top edge, not its middle: on a screen whose own
    # controls end low the bar sits so far down that a drag from the middle
    # would have to end off the screen, and that swipe is thrown away.
    y=$(printf '%s' "$p" | cut -d' ' -f4)
    y=$(( y + 20 ))
    # Downwards: that is the SnackBar's dismiss direction, and with an
    # accessibility client attached (uiautomator is one) a snackbar never
    # times out on its own, so this is the only way it goes.
    A shell input swipe "$x" "$y" "$x" 2390 250
    sleep 2
    if wait_gone "$SNACK" 12; then return 0; fi
  done
  say "a snackbar will not go away; the next shot may show it"
}

