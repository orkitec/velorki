# The two Velorki Plus screens and the cycle map's two (New York's map with
# the cycle map and stops on, and the Layers sheet) come from the Play capture
# rather than from tapping: the assistant's card needs Plus, consent and an answer from the
# relay, which `integration_test/store/store_screenshots_test.dart` poses with
# the relay mocked in the test process, and the Plus page is shown there as a
# subscriber sees it (`paywall-active`), with no price on it. That test runs
# on this same emulator profile at 1080x2400 with the status bar in the same
# demo mode, in the app's default accent, so only the volt looks have them:
#   tool/store_screenshots.sh --platform android --locales <lang> --until paywall
# The site shows another accent's frame in volt of the same mode.
STORE_RAW="${VELORKI_STORE_RAW:-$PWD/build/store_screenshots/android/raw}"

cap_from_store() {  # cap_from_store <mode-accent> <screen> <store shot>
  local mode=${1%%-*} accent=${1#*-} from
  from="$STORE_RAW/$mode/$LANG_TAG/$3.png"
  if [ "$accent" != volt ]; then
    say "    $2 is taken in volt only; skipped"
    return 0
  fi
  [ -f "$from" ] || die "no $from; run tool/store_screenshots.sh --platform android --locales $LANG_TAG --until paywall"
  mkdir -p "$OUT/$LANG_TAG/$1"
  cp "$from" "$OUT/$LANG_TAG/$1/$2.png"
  printf '    %s/%s/%s.png (from the Play capture)\n' "$LANG_TAG" "$1" "$2"
}

capture_look() {  # capture_look <mode-accent>
  local look=$1 mode=${1%%-*} accent=${1#*-}
  say "appearance: $mode + $accent"
  restart_with "$mode" "$accent"
  local screen
  for screen in "${SCREENS[@]}"; do
    say "  $screen"
    case "$screen" in
      planner) cap_planner "$look" ;;
      loop) cap_loop "$look" ;;
      search) cap_search "$look" ;;
      navigation) cap_navigation "$look" ;;
      recording) cap_recording "$look" ;;
      ride) cap_ride "$look" ;;
      library) cap_library "$look" ;;
      offline) cap_offline "$look" ;;
      settings) cap_settings "$look" ;;
      assistant) cap_from_store "$look" assistant ai ;;
      paywall) cap_from_store "$look" paywall paywall-active ;;
      cyclemap) cap_from_store "$look" cyclemap cyclemap ;;
      layers) cap_from_store "$look" layers layers ;;
      *) die "unknown screen $screen" ;;
    esac
  done
}

write_manifest() {
  say "writing $OUT/manifest.json"
  VELORKI_SHOT_RES="$RES" VELORKI_SHOT_DENSITY="$DENSITY" \
    VELORKI_SHOT_LOOKS="${ALL_LOOKS[*]}" VELORKI_SHOT_SCREENS="${ALL_SCREENS[*]}" \
    python3 - "$OUT" << 'PY'
import datetime, json, os, sys

out = sys.argv[1]
looks = os.environ["VELORKI_SHOT_LOOKS"].split()
screens = os.environ["VELORKI_SHOT_SCREENS"].split()
width, height = os.environ["VELORKI_SHOT_RES"].split("x")
# English, in every language: these describe the shot, not what the app says
# in it. The site's own alt texts are translated in web/messages/*.json.
titles = {
    "planner": "Planning the Funchal coast and Monte loop",
    "loop": "Smart Loop, a ride of about the length you asked for",
    "search": "Searching the offline gazetteer",
    "navigation": "Turn-by-turn guidance while recording",
    "recording": "A ride being recorded",
    "ride": "A finished ride, with its charts and splits",
    "library": "Saved routes and rides",
    "offline": "Offline map and routing data",
    "settings": "Settings, with the appearance block",
    "assistant": "The assistant's card, with the loop it asked for",
    "paywall": "Velorki Plus as a subscriber sees it",
    "cyclemap": "The offline cycle map and stops in Chelsea, New York",
    "layers": "The Layers sheet with the cycle map's parts",
}
# Every language with a set on disk, not only the one this run took: a German
# run must leave the English sets in the manifest. English first, the rest
# alphabetically.
languages = sorted(
    name
    for name in os.listdir(out)
    if any(os.path.isdir(os.path.join(out, name, look)) for look in looks)
)
languages.sort(key=lambda tag: (tag != "en", tag))

sets = []
for language in languages:
    for look in looks:
        mode, accent = look.split("-", 1)
        shots = []
        for screen in screens:
            relative = f"{language}/{look}/{screen}.png"
            path = os.path.join(out, relative)
            if not os.path.exists(path):
                continue
            shots.append({
                "screen": screen,
                "title": titles[screen],
                "file": relative,
                "bytes": os.path.getsize(path),
            })
        if shots:
            sets.append({
                "language": language,
                "mode": mode,
                "accent": accent,
                "screenshots": shots,
            })

manifest = {
    "generatedAt": datetime.datetime.now(datetime.timezone.utc)
        .strftime("%Y-%m-%dT%H:%M:%SZ"),
    "device": {
        "name": "Android emulator, Pixel-class phone",
        "platform": "android",
        "width": int(width),
        "height": int(height),
        "density": int(os.environ["VELORKI_SHOT_DENSITY"]),
        "statusBar": "SystemUI demo mode: 09:41, full battery, Wi-Fi, no notifications",
    },
    "region": {
        "name": "Funchal, Madeira",
        "routingTile": "W20_N30",
        "demoRoute": "Funchal coast and Monte route",
        "demoRide": "Funchal coast and Monte loop",
        "navigationRoute": "Funchal to Monte",
    },
    "languages": languages,
    "sets": sets,
}
with open(os.path.join(out, "manifest.json"), "w") as fh:
    json.dump(manifest, fh, indent=2)
    fh.write("\n")
PY
}

