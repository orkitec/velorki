cap_navigation() {
  A emu geo fix "$(head -2 "$WORK/monte.path" | tail -1 | cut -d, -f2)" \
    "$(head -2 "$WORK/monte.path" | tail -1 | cut -d, -f1)" > /dev/null
  sleep 3
  start_ride "Funchal to Monte"
  ride_along "$WORK/monte.path" 18
  # Ride for a while first, so the panel shows a believable distance rather
  # than the first hundred metres.
  sleep 90
  # Then wait for a turn that is close enough to read as guidance but not so
  # close that the banner has already switched to the one after it.
  local i turn far
  for ((i = 0; i < 60; i++)); do
    dump || true
    turn=$(python3 "$HERE/ui.py" grep "$WORK/ui.xml" "$(ui turn)" || true)
    far=$(python3 "$HERE/ui.py" grep "$WORK/ui.xml" "$(ui metres)" || true)
    far=${far//[^0-9]/}
    if [ -n "$turn" ] && [ -n "$far" ] && [ "$far" -ge 80 ] && [ "$far" -le 350 ]; then
      break
    fi
    sleep 3
  done
  [ -n "$turn" ] || say "no turn instruction appeared; capturing whatever the banner shows"
  wait_for "$(ui RECORDING)" 40 || say "the recorder is not in the RECORDING state"
  shot "$1" navigation
  stop_riding
  stop_ride
}

