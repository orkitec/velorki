keyboard_up() { [ "$(A shell dumpsys input_method | tr -d '\r' | grep -c 'mInputShown=true')" -gt 0 ]; }

type_text() {  # letters and spaces only; a capital taps shift first
  local s=$1 i c
  for ((i = 0; i < ${#s}; i++)); do
    c=${s:i:1}
    if [ "$c" = " " ]; then
      tap_xy "${KEY_SPACE[@]}"
      sleep 0.3
      continue
    fi
    if [[ $c =~ [A-Z] ]]; then
      tap_xy "${KEY_SHIFT[@]}"
      sleep 0.3
      c=${c,}
    fi
    tap_xy "${KEYX[$c]}" "${KEYY[$c]}"
    sleep 0.35
  done
}

erase() { local n=$1 i; for ((i = 0; i < n; i++)); do tap_xy "${KEY_BACKSPACE[@]}"; sleep 0.2; done; }

hide_keyboard() {
  if keyboard_up; then
    tap_xy "${KEY_HIDE[@]}"
    sleep 2
  fi
}

# ------------------------------------------------------------ shared_prefs

DOUBLE_PREFIX='VGhpcyBpcyB0aGUgcHJlZml4IGZvciBEb3VibGUu'

set_prefs() {  # set_prefs key=value ...  (the app is stopped and left stopped)
  local kv entries=""
  for kv in "$@"; do
    entries+="    <string name=\"flutter.${kv%%=*}\">${kv#*=}</string>"$'\n'
  done
  A shell am force-stop "$PKG"
  sleep 2
  A shell "run-as $PKG sh -c 'cat > shared_prefs/FlutterSharedPreferences.xml'" << XML
<?xml version='1.0' encoding='utf-8' standalone='yes' ?>
<map>
$entries</map>
XML
}

launch() {
  A shell am force-stop "$PKG"
  sleep 2
  A shell am start -n "$PKG/.MainActivity" > /dev/null
  # The floating tab bar is on every tab, so it says the shell is up whatever
  # the app opens on.
  wait_for "$(ui tabbar)" 90 "the app did not come up"
  sleep 5
}

# The app's own language, patched into the prefs file rather than written over
# it: this runs before the seeding, which taps its way through the very same
# translated labels, and again at the end of a run to hand the emulator back on
# System. English is the absence of the key; `set_prefs` rewrites the whole
# file, so `restart_with` puts the key back for every appearance.
set_language() {  # set_language <tag|en>
  say "app language: ${1/#en/System (English)}"
  A shell am force-stop "$PKG"
  sleep 2
  A shell "run-as $PKG cat shared_prefs/FlutterSharedPreferences.xml" \
    > "$WORK/prefs.xml" 2> /dev/null || : > "$WORK/prefs.xml"
  VELORKI_LANG="$1" python3 - "$WORK/prefs.xml" << 'PY'
import os, re, sys

path, tag = sys.argv[1], os.environ["VELORKI_LANG"]
body = open(path).read()
if "<map" not in body:
    body = ("<?xml version='1.0' encoding='utf-8' standalone='yes' ?>\n"
            "<map>\n</map>\n")
body = body.replace("<map />", "<map>\n</map>").replace("<map/>", "<map>\n</map>")
body = re.sub(r'\s*<string name="flutter\.language\.locale">[^<]*</string>', "", body)
if tag not in ("en", "system"):
    body = body.replace(
        "<map>",
        f'<map>\n    <string name="flutter.language.locale">{tag}</string>', 1)
open(path, "w").write(body)
PY
  A shell "run-as $PKG sh -c 'cat > shared_prefs/FlutterSharedPreferences.xml'" < "$WORK/prefs.xml"
}

restart_with() {  # restart_with <mode> <accent>
  # Android's own theme too, so the on-screen keyboard in the search shot
  # matches the app rather than glaring white over a dark map.
  if [ "$1" = dark ]; then
    A shell cmd uimode night yes > /dev/null
  else
    A shell cmd uimode night no > /dev/null
  fi
  sleep 2
  local prefs=(
    "appearance.mode=$1"
    "appearance.accent=$2"
    "appearance.map=auto"
    "units.system=metric"
    "map.camera.lat=${DOUBLE_PREFIX}32.682"
    "map.camera.lon=${DOUBLE_PREFIX}-16.929"
    "map.camera.zoom=${DOUBLE_PREFIX}11.4"
  )
  # The whole file is rewritten, so the language has to come along; leaving it
  # out is what English (System) is.
  [ "$LANG_TAG" = en ] || prefs+=("language.locale=$LANG_TAG")
  set_prefs "${prefs[@]}"
  launch
}

# ------------------------------------------------------------- the app build

BANNER_MARK='      // VELORKI_SCREENSHOTS: taken out again as soon as the build is done.'

restore_banner() {
  [ -f lib/app/app.dart ] || return 0
  grep -q 'VELORKI_SCREENSHOTS' lib/app/app.dart || return 0
  python3 - << 'PY'
path = "lib/app/app.dart"
mark = "      // VELORKI_SCREENSHOTS: taken out again as soon as the build is done.\n"
flag = "      debugShowCheckedModeBanner: false,\n"
body = open(path).read().replace(mark + flag, "", 1)
open(path, "w").write(body)
PY
}
trap 'restore_banner; rm -rf "$WORK"' EXIT

build_and_install() {
  say "building the debug APK"
  restore_banner
  python3 - << 'PY'
path = "lib/app/app.dart"
mark = "      // VELORKI_SCREENSHOTS: taken out again as soon as the build is done.\n"
flag = "      debugShowCheckedModeBanner: false,\n"
body = open(path).read()
assert "return MaterialApp.router(\n" in body, "lib/app/app.dart no longer starts the app the way this script expects"
open(path, "w").write(body.replace("return MaterialApp.router(\n",
                                   "return MaterialApp.router(\n" + mark + flag, 1))
PY
  local rc=0
  mise exec -- flutter build apk --debug --dart-define-from-file=env/local.json || rc=$?
  restore_banner
  [ "$rc" -eq 0 ] || die "the debug build failed"
  say "installing on $SERIAL"
  A install -r build/app/outputs/flutter-apk/app-debug.apk > /dev/null
  for p in ACCESS_FINE_LOCATION ACCESS_COARSE_LOCATION POST_NOTIFICATIONS; do
    A shell pm grant "$PKG" "android.permission.$p" 2> /dev/null || true
  done
}

start_mirror() {
  if curl -fsS http://127.0.0.1:8000/manifest.json > /dev/null 2>&1; then
    say "the tile mirror is already serving on port 8000"
    return
  fi
  say "starting the tile mirror"
  bash tool/itest_mirror.sh > /dev/null
}

# --------------------------------------------------------------- the seeding

db() {  # db <sql> -> one value per line
  # Drift runs SQLite in WAL mode, so the newest rows are in the -wal file
  # rather than the database: copying only the database reads a state that is
  # a few writes behind, which looks exactly like an import that never
  # happened.
  A shell "run-as $PKG cat app_flutter/velorki.sqlite" > "$WORK/velorki.sqlite" 2> /dev/null || return 1
  A shell "run-as $PKG cat app_flutter/velorki.sqlite-wal" > "$WORK/velorki.sqlite-wal" 2> /dev/null || true
  A shell "run-as $PKG cat app_flutter/velorki.sqlite-shm" > "$WORK/velorki.sqlite-shm" 2> /dev/null || true
  python3 - "$WORK/velorki.sqlite" "$1" << 'PY'
import sqlite3, sys
try:
    for row in sqlite3.connect(sys.argv[1]).execute(sys.argv[2]):
        print("|".join("" if v is None else str(v) for v in row))
except sqlite3.Error:
    pass
PY
}

has_row() { [ -n "$(db "$1" 2> /dev/null)" ]; }

push_gpx() {  # into the app's own files dir, the one place it may read from
  local name=$1
  A push "$HERE/$name" "/sdcard/Download/$name" > /dev/null
  A shell "run-as $PKG sh -c 'cat > files/$name' < /sdcard/Download/$name"
}

import_gpx() {  # import_gpx <file> <Route|Ride> <expected row name>
  local file=$1 kind=$2
  push_gpx "$file"
  # A fresh process: the import preview is reached from the launch intent, and
  # a snackbar left over from an earlier screen would cover the Save button.
  A shell am force-stop "$PKG"
  sleep 3
  A shell am start -a android.intent.action.VIEW \
    -d "file://$APP_FILES/$file" -t application/gpx+xml "$PKG" > /dev/null
  wait_for "$(ui import)" 90 "the import preview did not open for $file"
  wait_for "$(ui save)" 60
  sleep 4
  tap "$(ui "kind_$kind")"
  sleep 2
  dismiss_snackbar
  tap "$(ui save)"
  sleep 10
}

seed_tile() {
  if has_row "select name from routing_tiles where name = 'W20_N30' and state = 'ready'"; then
    say "the W20_N30 routing tile is already on the device"
    return
  fi
  say "downloading the Madeira routing tile and the map area"
  A emu geo fix -16.9075 32.6465 > /dev/null
  sleep 2
  tap "$(ui locate)"
  sleep 8
  tap "$(ui offline_entry)"
  wait_for "$(ui download_visible)" 30
  tap "$(ui download_visible)"
  wait_for "$(ui download)" 30
  tap "$(ui download)"
  for _ in $(seq 1 30); do
    if has_row "select name from routing_tiles where state = 'ready'"; then break; fi
    sleep 5
  done
  has_row "select name from routing_tiles where state = 'ready'" \
    || die "the routing tile did not download; is the mirror on port 8000 up?"
  sleep 10
  tap "$(ui back)" || true
  sleep 3
}

