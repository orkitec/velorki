#!/usr/bin/env bash
# Takes the product screenshots the website shows, on the Android emulator.
#
#   tool/screenshots.sh                 # build, seed, capture the whole matrix
#   tool/screenshots.sh --no-build      # keep the installed app
#   tool/screenshots.sh --no-seed       # keep the demo route, ride and tile
#   tool/screenshots.sh --only dark-volt # one appearance only (repeatable)
#   tool/screenshots.sh --screens planner,settings   # only these screens
#   tool/screenshots.sh --lang de       # the app in German (default: en)
#
# Output: web/public/screenshots/<lang>/<mode>-<accent>/<screen>.png plus
# web/public/screenshots/manifest.json. Screens are planner, loop, search,
# navigation, recording, ride, library, offline and settings; the appearance
# matrix is light-volt, dark-volt, dark-ember, dark-glacier and dark-berry.
# One run takes one language; the manifest lists every language found on disk,
# so a German run leaves the English set alone.
#
# Requirements
# ------------
# * The `velorki` emulator, running and booted (`~/Work/bin/velorki-emu`);
#   the phone is never touched, the serial is fixed to emulator-5554 unless
#   VELORKI_SHOT_DEVICE says otherwise.
# * `mise` (Flutter 3.47 and Java 21), the Android platform tools, python3 and
#   `env/local.json` (git-ignored; it points the tile mirror at 10.0.2.2:8000).
# * Network: the map style and its raster tiles come from OpenFreeMap. Routing,
#   the gazetteer and the loop search all run on the device.
#
# How it works, and why
# ---------------------
# * **The tile mirror** (`tool/itest_mirror.sh`) serves the frozen oracle tile
#   W20_N30 — Madeira — on port 8000, the same one the integration suite uses
#   with VELORKI_ITEST_REGION=madeira. The app downloads it through its own
#   offline screen, so the routing in every shot is the on-device engine.
# * **The debug banner** is patched out of `lib/app/app.dart` for the length of
#   the build and put back immediately afterwards (a debug build is required:
#   `env/local.json` points at a cleartext mirror, which a profile build
#   blocks). The marker line is removed again by `restore_banner`, which also
#   runs from the EXIT trap, so an interrupted run leaves the tree clean.
# * **The demo data** is two GPX files in tool/screenshots/, regenerated by
#   `gen_demo_gpx.py`: a 24.5 km loop around Funchal as a `<trk>` with
#   timestamps (imported as a ride) and the same loop as a `<rte>` (imported as
#   a route). The track is sampled every ten seconds rather than every N
#   metres: the app measures an imported ride exactly like a recorded one, and
#   a gap of over 30 s between two fixes counts as a break that contributes
#   neither distance nor moving time (`lib/core/geo/ride_stats.dart`), so a
#   sparse track loses every slow climb.
# * **Getting a file into the app.** `file:///sdcard/Download/...` does not
#   work on API 33+: the intent reaches the activity, but scoped storage stops
#   the app reading the path, and the URI then falls through to go_router as an
#   unknown deep link ("Page Not Found"). A MediaStore `content://` URI is one
#   way round it; the shorter one, used here, is `adb shell run-as` to copy the
#   file into the app's own files directory and to point the VIEW intent at
#   that path, which the app may read.
# * **The language** is the app's own setting, never the system's: the key
#   `flutter.language.locale` in the same shared_prefs file, holding a language
#   tag. English is the absence of the key — that is what "System" means to
#   `LanguageSetting` — and the key is taken out again at the end of every run,
#   so the emulator is handed back on System. Every label the script waits for
#   or taps is translated too, so the selectors live in one table (`UI`) keyed
#   by language; a name with no entry for the language falls back to English,
#   which is right for the demo route and ride names: proper nouns, seeded
#   once and never re-imported per language.
# * **Appearance** is written straight into `shared_prefs/FlutterSharedPreferences.xml`
#   through `run-as`, with the app force-stopped first — shared_preferences
#   holds the map in memory and would write it back over anything changed
#   underneath it. The same file seeds the map camera, so every shot starts
#   over Funchal instead of wherever the last run left the map.
# * **Typing** happens by tapping the on-screen keyboard, never with
#   `adb shell input text`. A key event puts the window into Android's
#   focus-highlight mode, which then draws an accent-coloured border around the
#   whole window until the app is restarted — and that border lands in every
#   screenshot after it.
# * **The turn banner** needs a routed route: an imported GPX carries no turn
#   instructions, so following it only ever says "Continue". The seed therefore
#   plans Funchal → Monte with the on-device router, saves it, and reads its
#   geometry back out of the app database with `screenshots/unpack_route.py` so
#   `tool/emu_ride.py --path` can ride exactly that line.
#
# The script is idempotent: it skips the seeding steps whose result is already
# in the app database, and re-taking one screen overwrites one file.
set -euo pipefail

cd "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ROOT="$(cd .. && pwd)"
HERE="$PWD/tool/screenshots"
OUT="${VELORKI_SHOT_OUT:-$ROOT/web/public/screenshots}"
SERIAL="${VELORKI_SHOT_DEVICE:-emulator-5554}"
PKG=com.orkitec.velorki
APP_FILES="/data/user/0/$PKG/files"
WORK="$(mktemp -d)"
export PATH="$HOME/Android/Sdk/platform-tools:$PATH"

ALL_SCREENS=(planner loop search navigation recording ride library offline settings)
ALL_LOOKS=(light-volt dark-volt dark-ember dark-glacier dark-berry)
DO_BUILD=1
DO_SEED=1
LANG_TAG=en
LOOKS=()
SCREENS=()

while [ $# -gt 0 ]; do
  case "$1" in
    --no-build) DO_BUILD=0 ;;
    --no-seed) DO_SEED=0 ;;
    --only) IFS=, read -r -a extra <<< "$2"; LOOKS+=("${extra[@]}"); shift ;;
    --screens) IFS=, read -r -a SCREENS <<< "$2"; shift ;;
    --lang) LANG_TAG="$2"; shift ;;
    -h | --help) sed -n '2,/^set -euo/p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//;$d'; exit 0 ;;
    *) printf 'unknown argument %q\n' "$1" >&2; exit 2 ;;
  esac
  shift
done
if [ ${#LOOKS[@]} -eq 0 ]; then LOOKS=("${ALL_LOOKS[@]}"); fi
if [ ${#SCREENS[@]} -eq 0 ]; then SCREENS=("${ALL_SCREENS[@]}"); fi
[[ $LANG_TAG =~ ^[a-z]{2,3}([-_][A-Za-z0-9]+)*$ ]] \
  || { printf 'not a language tag: %q\n' "$LANG_TAG" >&2; exit 2; }

say() { printf '==> %s\n' "$*"; }
die() { printf '::error::%s\n' "$*" >&2; exit 1; }
A() { adb -s "$SERIAL" "$@"; }

# ---------------------------------------------------------------- the device

require_device() {
  command -v adb > /dev/null || die "adb is not on PATH (\$HOME/Android/Sdk/platform-tools)."
  if ! adb devices | grep -q "^$SERIAL[[:space:]]*device$"; then
    die "$SERIAL is not attached. Start it with ~/Work/bin/velorki-emu and wait for sys.boot_completed."
  fi
  [ "$(A shell getprop sys.boot_completed | tr -d '\r')" = 1 ] || die "$SERIAL has not finished booting."
  RES="$(A shell wm size | tr -d '\r' | awk '{print $NF}')"
  [ "$RES" = "1080x2400" ] || say "warning: this screen is $RES; the keyboard and pan offsets are tuned for 1080x2400."
  DENSITY="$(A shell wm density | tr -d '\r' | awk '{print $NF}')"
}

