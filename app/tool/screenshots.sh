seed() {
  say "seeding the demo state"
  launch
  seed_tile
  if has_row "select id from routes where name = 'Funchal coast and Monte route'"; then
    say "the demo route is already in the library"
  else
    import_gpx demo-route.gpx Route
  fi
  if has_row "select id from rides where name = 'Funchal coast and Monte loop'"; then
    say "the demo ride is already in the library"
  else
    import_gpx demo-loop.gpx Ride
  fi
  # A few shorter files as well, so the library and the Record tab's recent
  # rides do not read as a fresh install.
  seed_extra routes "Praia Formosa and back" demo-formosa.gpx Route
  seed_extra routes "Monte and the Levada dos Tornos" demo-levada.gpx Route
  seed_extra rides "Evening seafront spin" demo-seafront.gpx Ride
  seed_extra rides "Camara de Lobos climb" demo-camara.gpx Ride
  seed_navigation_route
  # The rider's line for the plain recording shot: the first couple of
  # kilometres of the demo loop, along the Funchal seafront.
  head -14 "$HERE/demo-loop.path" > "$WORK/seafront.path"
}

# ------------------------------------------------------------ the status bar

demo_mode() {
  say "putting the status bar into demo mode"
  A shell settings put global sysui_demo_allowed 1
  local d="am broadcast -a com.android.systemui.demo"
  A shell $d -e command enter > /dev/null
  A shell $d -e command clock -e hhmm 0941 > /dev/null
  A shell $d -e command battery -e level 100 -e plugged false > /dev/null
  A shell $d -e command network -e wifi show -e level 4 -e fully true > /dev/null
  A shell $d -e command network -e mobile hide > /dev/null
  A shell $d -e command notifications -e visible false > /dev/null
  A shell $d -e command status -e volume hide -e bluetooth hide -e location hide \
    -e alarm hide -e sync hide -e tty hide -e eri hide -e mute hide -e speakerphone hide > /dev/null
  sleep 2
}

demo_mode_off() {
  say "leaving demo mode"
  A shell am broadcast -a com.android.systemui.demo -e command exit > /dev/null || true
  # The dark captures put Android itself into night mode; hand the emulator
  # back the way it was found.
  A shell cmd uimode night no > /dev/null || true
}

# -------------------------------------------------------------- the captures

shot() {  # shot <mode-accent> <screen>
  local dir="$OUT/$LANG_TAG/$1"
  mkdir -p "$dir"
  dismiss_snackbar
  sleep 1
  A exec-out screencap -p > "$dir/$2.png"
  local bytes
  bytes=$(stat -c%s "$dir/$2.png")
  [ "$bytes" -gt 20000 ] || die "$dir/$2.png came out empty ($bytes bytes)"
  printf '    %s/%s/%s.png (%s kB)\n' "$LANG_TAG" "$1" "$2" "$(( bytes / 1024 ))"
}

go_tab() {
  # The bar is not drawn while the keyboard is up, and the search field takes
  # the focus back when a pushed screen is popped, so put the keyboard away
  # before looking for a tab.
  hide_keyboard
  # Twice: the first tap switches branch, the second pops that branch back to
  # its root, because a screen pushed inside a tab (a route detail, say) stays
  # on its stack when another tab is shown.
  tap "^$1"
  sleep 2
  tap "^$1"
  sleep 4
}

clear_plan() {  # the action row is one merged semantics node; Clear is 3rd of 5
  local i p x1 y1 x2 y2
  go_tab "$(ui tab_plan)"
  # Up to three goes: the sheet is not always built by the time the tab
  # switch settles, and a ride that was re-routed puts its new line back into
  # the plan, which would otherwise be followed by the next "No route" ride.
  for i in 1 2 3; do
    sleep 3
    # The empty-plan headline. Checking for DISTANCE instead would miss a plan
    # that holds one lone waypoint and no route, which is enough to make the
    # Record tab offer "The route on the Plan tab" rather than "No route".
    if has "$(ui empty_plan)"; then return 0; fi
    p=$(node "$(ui undo)") || return 0
    read -r _ _ x1 y1 x2 y2 <<< "$p"
    tap_xy "$(( x1 + (x2 - x1) * 5 / 10 ))" "$(( y1 + (y2 - y1) * 35 / 100 ))"
    sleep 3
  done
  say "the plan would not clear"
}

